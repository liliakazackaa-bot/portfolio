export type ServiceId = 'site' | 'app' | 'agent' | 'unknown';
export type Direction = Exclude<ServiceId, 'unknown'>;

export interface Service {
  id: Direction;
  num: string;
  label: string;
  pain: string;
  title: string;
  text: string;
  price: string;
  term: string;
  cta: string;
  color: 'cyan' | 'magenta' | 'lime';
}

export interface Project {
  title: string;
  service: Direction;
  task: string;
  solution: string;
  outcome: string;
  stack: string[];
  demoUrl?: string;
  /** Реальный проект: бейдж «проект» и ссылка «открыть сайт». */
  real?: boolean;
}

export interface Step {
  num: string;
  tag: string;
  title: string;
  text: string;
}

export interface Faq {
  q: string;
  a: string;
}

export interface ChatLine {
  from: 'client' | 'agent' | 'system';
  text: string;
}

export interface Stat {
  value: number;
  prefix?: string;
  suffix: string;
  label: string;
  /** false — показать как есть, без накрутки (например, 24/7). */
  animate?: boolean;
}

